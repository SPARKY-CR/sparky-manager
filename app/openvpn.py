"""OpenVPN server + client config rendering (written from scratch).

Server model: username/password auth only (no per-user client
certificates). The server verifies credentials through the
``auth-user-pass-verify`` script (``scripts/ovpn-auth.py``), which
checks the username/password against the panel database, and
``client-cert-not-required`` lets clients connect without a client
certificate (the directive is deprecated in OpenVPN 2.6 in favour
of ``verify-client-cert none`` but still accepted there, and it is
the only form OpenVPN 2.5 on Ubuntu 22.04 understands — the panel
supports 22.04/24.04/26.04, so compatibility wins).

The server needs a CA + server certificate; those live under the
panel data dir (``data/ca/``, generated by the installer with
openssl) and are shared with IKEv2 / ocserv — one CA, one server
cert (SAN = the host clients dial), so there is a single trust
anchor to embed in client files. The ``.ovpn`` embeds the CA cert
and prompts for username/password (``auth-user-pass`` with no file
argument) — the same file works for every user of the inbound.

There is no share-link standard for OpenVPN and sing-box has no
OpenVPN outbound, so OpenVPN appears in neither subscription feed;
it is exported as the ``.ovpn`` file (bundle entry
``openvpn_config`` + the token-gated ``/sub/<token>/openvpn.ovpn``
download) and as a QR of its content.
"""

from __future__ import annotations

import ipaddress
from pathlib import Path

__all__ = [
    "DEFAULT_NETWORK",
    "DEFAULT_PORT",
    "render_client_config",
    "render_server_config",
    "validate_server_config",
]

DEFAULT_PORT = 1194
DEFAULT_NETWORK = "10.9.0.0/24"
DEFAULT_AUTH_SCRIPT = "/opt/sparky-manager/scripts/ovpn-auth.py"

# Directives the rendered server config must contain (checked by
# validate_server_config); the values are checked separately.
_REQUIRED_DIRECTIVES = (
    "port",
    "proto",
    "dev",
    "ca",
    "cert",
    "key",
    "server",
    "auth-user-pass-verify",
    "cipher",
)


def _network_netmask(network: str) -> tuple[str, str]:
    """``10.9.0.0/24`` -> ``("10.9.0.0", "255.255.255.0")``."""
    net = ipaddress.ip_network(network, strict=False)
    return str(net.network_address), str(net.netmask)


def render_server_config(
    *,
    port: int = DEFAULT_PORT,
    proto: str = "udp",
    network: str = DEFAULT_NETWORK,
    ca_cert: str,
    server_cert: str,
    server_key: str,
    auth_script: str = DEFAULT_AUTH_SCRIPT,
    status_dir: str = "/var/log/openvpn",
    dns: tuple[str, str] = ("1.1.1.1", "1.0.0.1"),
) -> str:
    """Render an OpenVPN server config (``server`` directive form).

    ``network`` is the client subnet (CIDR); ``proto`` is ``udp``
    (default) or ``tcp``. The server pushes a full-tunnel default
    route and the panel DNS servers to clients.
    """
    proto = proto.lower().strip()
    if proto not in ("udp", "tcp"):
        proto = "udp"
    net_addr, netmask = _network_netmask(network)
    lines = [
        f"port {int(port)}",
        f"proto {proto}",
        "dev tun",
        f"ca {ca_cert}",
        f"cert {server_cert}",
        f"key {server_key}",
        "dh none",
        f"server {net_addr} {netmask}",
        "topology subnet",
        f"ifconfig-pool-persist {status_dir}/ipp.txt",
        'push "redirect-gateway def1 bypass-dhcp"',
    ]
    for server in dns:
        lines.append(f'push "dhcp-option DNS {server}"')
    lines += [
        "keepalive 10 120",
        "cipher AES-256-GCM",
        "auth SHA256",
        "tls-version-min 1.2",
        # Password-only auth: no client certificate is required; the
        # verify script checks the credentials against the panel DB.
        "client-cert-not-required",
        "username-as-common-name",
        f"auth-user-pass-verify {auth_script} via-file",
        "user nobody",
        "group nogroup",
        "persist-key",
        "persist-tun",
        f"status {status_dir}/openvpn-status.log",
        f"log-append {status_dir}/openvpn.log",
        "verb 3",
    ]
    if proto == "udp":
        lines.append("explicit-exit-notify 1")
    return "\n".join(lines) + "\n"


def render_client_config(
    *,
    host: str,
    port: int = DEFAULT_PORT,
    proto: str = "udp",
    ca_cert_pem: str,
    name: str = "sparky-manager",
) -> str:
    """Render a client ``.ovpn`` file (CA embedded, password prompt).

    ``ca_cert_pem`` is the PEM text of the panel CA (the server
    cert chains to it). The client enters username/password when
    connecting — the same file works for every user of the inbound.
    """
    proto = proto.lower().strip()
    if proto not in ("udp", "tcp"):
        proto = "udp"
    host = host.strip()
    if ":" in host and not host.startswith("["):
        host = f"[{host}]"
    pem = (ca_cert_pem or "").strip()
    if pem and not pem.endswith("\n"):
        pem += "\n"
    lines = [
        "# " + name,
        "client",
        "dev tun",
        f"proto {proto}",
        f"remote {host} {int(port)}",
        "resolv-retry infinite",
        "nobind",
        "persist-key",
        "persist-tun",
        "auth-user-pass",
        "remote-cert-tls server",
        "cipher AES-256-GCM",
        "auth SHA256",
        "tls-version-min 1.2",
        "verb 3",
        "<ca>",
        pem.rstrip("\n"),
        "</ca>",
    ]
    return "\n".join(lines) + "\n"


def _directive_values(text: str) -> dict[str, list[str]]:
    """Parse ``directive args`` lines into ``{directive: [args...]}``."""
    out: dict[str, list[str]] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith(";"):
            continue
        parts = line.split(None, 1)
        key = parts[0].lower()
        out.setdefault(key, []).append(parts[1].strip() if len(parts) > 1 else "")
    return out


def validate_server_config(
    text: str,
    *,
    ca_cert: str = "",
    server_cert: str = "",
    server_key: str = "",
    auth_script: str = "",
) -> list[str]:
    """Structural validation of a rendered server config.

    Checks the required directives are present, the port / proto /
    server subnet are valid, and the referenced CA / cert / key /
    auth-script files exist. This is the panel's own validator —
    OpenVPN has no config dry-run mode (``openvpn --config`` would
    try to start the server), so the real check is the service
    restart, whose output the panel now captures (see
    ``app.main._restart_service`` + the journal tail).
    """
    problems: list[str] = []
    if not text.strip():
        return ["config is empty"]
    directives = _directive_values(text)
    for required in _REQUIRED_DIRECTIVES:
        if required not in directives:
            problems.append(f"config is missing the '{required}' directive")
    port = (directives.get("port") or [""])[0]
    if port:
        try:
            port_n = int(port)
        except ValueError:
            problems.append(f"port is not a number: {port!r}")
        else:
            if not 1 <= port_n <= 65535:
                problems.append(f"port out of range: {port_n}")
    proto = (directives.get("proto") or [""])[0].lower()
    if proto and proto not in ("udp", "tcp", "udp4", "udp6", "tcp4", "tcp6"):
        problems.append(f"proto is not udp/tcp: {proto!r}")
    server = (directives.get("server") or [""])[0]
    if server:
        parts = server.split()
        if len(parts) != 2:
            problems.append(f"server directive is not '<network> <netmask>': {server!r}")
        else:
            try:
                ipaddress.ip_network(f"{parts[0]}/{parts[1]}", strict=False)
            except ValueError:
                problems.append(f"server subnet is invalid: {server!r}")
    for label, expected, path in (
        ("ca", ca_cert, (directives.get("ca") or [""])[0]),
        ("cert", server_cert, (directives.get("cert") or [""])[0]),
        ("key", server_key, (directives.get("key") or [""])[0]),
    ):
        if expected and path and path != expected:
            problems.append(
                f"{label} path {path!r} does not match the expected {expected!r}"
            )
        target = path or expected
        if target and not Path(target).is_file():
            problems.append(f"{label} file does not exist: {target}")
    verify = (directives.get("auth-user-pass-verify") or [""])[0]
    if verify:
        script = verify.split()[0]
        if auth_script and script != auth_script:
            problems.append(
                f"auth-user-pass-verify script {script!r} does not match {auth_script!r}"
            )
        if not Path(script).is_file():
            problems.append(f"auth script does not exist: {script}")
        elif not Path(script).stat().st_mode & 0o111:
            problems.append(f"auth script is not executable: {script}")
    return problems
