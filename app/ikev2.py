"""Native IKEv2 (strongSwan, swanctl/VICI) rendering (written from scratch).

Server model: EAP-MSCHAPv2 with a server certificate — one
connection (``remote-access``) for every user, one EAP secret per
user (``eap-user-<id>`` with ``id = <username>``). The server
certificate is the panel's shared server cert (``data/ca/``,
generated by the installer; SAN = the host clients dial, RSA,
SHA-256, EKU serverAuth), the CA is the panel's CA — the same
trust anchor OpenVPN uses.

Config format is ``swanctl.conf`` (the current VICI style;
``ipsec.conf`` / stroke has been deprecated since strongSwan
5.2.0). Applying is ``swanctl --load-all`` (the load itself is
the validator — there is no dry-run), verified with
``swanctl --list-conns``. Ports: UDP 500 (IKE) + UDP 4500 (NAT-T)
— both are reserved in the inbound form by design; an IKEv2
inbound's stored port is 500.

Client export: a ``.mobileconfig`` profile (plist) with a VPN
payload (``com.apple.vpn.managed``, ``VPNType = IKEv2``,
``AuthenticationMethod = Certificate`` + ``ExtendedAuthEnabled``,
EAP username/password embedded so iOS does not prompt) and a
second payload carrying the panel CA as a trusted root
(``com.apple.security.root``). SA parameters are AES-256 /
SHA2-256 / DH group 14, matching the server's
``aes256-sha256-modp2048`` proposals. The profile is built with
``plistlib`` (stdlib), not hand-written XML.

There is no share-link standard for IKEv2 and sing-box has no
IKEv2 outbound, so it appears in neither subscription feed; it is
exported as the ``.mobileconfig`` file (bundle entry
``ikev2_mobileconfig`` + the token-gated
``/sub/<token>/ikev2.mobileconfig`` download).
"""

from __future__ import annotations

import base64
import ipaddress
import plistlib
import re
import uuid
from pathlib import Path
from typing import Any, Sequence

__all__ = [
    "DEFAULT_NETWORK",
    "DEFAULT_PORT",
    "load_ca_cert_der",
    "pem_to_der",
    "render_mobileconfig",
    "render_swanctl_config",
    "server_id_from_cert_pem",
    "validate_swanctl_config",
]

DEFAULT_PORT = 500
DEFAULT_NETWORK = "10.20.0.0/24"
CONNECTION_NAME = "remote-access"
POOL_NAME = "ipv4"


def _escape_secret(secret: str) -> str:
    """Escape a value for a double-quoted swanctl string."""
    return secret.replace("\\", "\\\\").replace('"', '\\"')


def render_swanctl_config(
    *,
    users: Sequence[tuple[int, str, str]],
    server_id: str,
    network: str = DEFAULT_NETWORK,
    dns: tuple[str, str] = ("1.1.1.1", "1.0.0.1"),
    server_cert_name: str = "server-cert.pem",
) -> str:
    """Render ``swanctl.conf`` for the IKEv2 road-warrior setup.

    ``users`` is ``(user_id, username, eap_password)`` triples; the
    section name is ``eap-user-<id>`` (numeric — usernames are
    free-form text and must not appear unquoted in section names).
    ``server_id`` is the identity clients dial (domain or IP) and
    must match the server certificate's SAN.
    """
    net = ipaddress.ip_network(network, strict=False)
    dns_list = ", ".join(dns)
    lines = [
        "# swanctl.conf rendered by sparky-manager — do not hand-edit.",
        "pools {",
        f"    {POOL_NAME} {{",
        f"        addrs = {net.network_address}/{net.prefixlen}",
        f"        dns = {dns_list}",
        "    }",
        "}",
        "",
        "connections {",
        f"    {CONNECTION_NAME} {{",
        "        version = 2",
        "        proposals = aes256-sha256-modp2048",
        "        dpd_delay = 30s",
        "        local {",
        "            auth = pubkey",
        f"            certs = {server_cert_name}",
        f"            id = {server_id}",
        "        }",
        "        remote {",
        "            auth = eap-mschapv2",
        "            eap_id = %any",
        "        }",
        "        children {",
        "            tunnel {",
        "                esp_proposals = aes256-sha256-modp2048",
        "                local_ts = 0.0.0.0/0",
        "                remote_ts = dynamic",
        "                dpd_action = clear",
        f"                pools = {POOL_NAME}",
        "            }",
        "        }",
        "    }",
        "}",
        "",
        "secrets {",
    ]
    for user_id, username, password in users:
        lines.append(f"    eap-user-{int(user_id)} {{")
        lines.append(f'        id = "{_escape_secret(username)}"')
        lines.append(f'        secret = "{_escape_secret(password)}"')
        lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def server_id_from_cert_pem(pem_text: str) -> str | None:
    """Server identity from a PEM cert: first DNS SAN, else first IP
    SAN, else the subject CN. Returns None when the cert cannot be
    parsed (or ``cryptography`` is unavailable) — the caller then
    falls back to the configured host.

    The identity clients dial must match the server certificate's
    SAN exactly, so reading it from the cert itself is the only way
    to guarantee the match.
    """
    try:
        from cryptography import x509
        from cryptography.x509.oid import NameOID
    except ImportError:
        return None
    try:
        cert = x509.load_pem_x509_certificate(pem_text.encode("utf-8"))
    except Exception:  # noqa: BLE001
        return None
    try:
        san = cert.extensions.get_extension_for_class(
            x509.SubjectAlternativeName
        ).value
    except x509.ExtensionNotFound:
        san = None
    if san is not None:
        dns_names = san.get_values_for_type(x509.DNSName)
        if dns_names:
            return str(dns_names[0])
        ip_names = san.get_values_for_type(x509.IPAddress)
        if ip_names:
            return str(ip_names[0])
    try:
        cn = cert.subject.get_attributes_for_oid(NameOID.COMMON_NAME)[0].value
    except (IndexError, AttributeError):
        return None
    return str(cn) if cn else None


def pem_to_der(pem_text: str) -> bytes | None:
    """Decode a PEM certificate to DER bytes (None when unparseable)."""
    body_lines = [
        line.strip()
        for line in (pem_text or "").splitlines()
        if line.strip() and not line.strip().startswith("-----")
    ]
    if not body_lines:
        return None
    try:
        return base64.b64decode("".join(body_lines), validate=True)
    except Exception:  # noqa: BLE001
        return None


def load_ca_cert_der(ca_cert_path: str | Path) -> bytes | None:
    """Read the panel CA certificate as DER bytes (None when missing)."""
    try:
        pem = Path(ca_cert_path).read_text(encoding="utf-8")
    except OSError:
        return None
    return pem_to_der(pem)


def render_mobileconfig(
    *,
    user_name: str,
    eap_password: str,
    server_host: str,
    server_id: str | None = None,
    ca_cert_der: bytes | None = None,
    profile_name: str = "sparky-manager",
    server_cn: str | None = None,
) -> bytes:
    """Render an iOS/macOS ``.mobileconfig`` profile (plist XML).

    The VPN payload uses certificate auth + EAP-MSCHAPv2 (username /
    password embedded); the CA payload installs the panel CA as a
    trusted root (iOS 13+ also needs the user to enable full trust
    for it in Settings — the docs say so). ``PayloadCertificateUUID``
    links the VPN payload to the CA payload.
    """
    server_id = (server_id or server_host).strip()
    server_cn = (server_cn or server_id).strip()
    ca_uuid = str(uuid.uuid4())
    ikev2: dict[str, Any] = {
        "RemoteAddress": server_host.strip(),
        "RemoteIdentifier": server_id,
        "LocalIdentifier": user_name,
        "AuthenticationMethod": "Certificate",
        "ExtendedAuthEnabled": True,
        "AuthName": user_name,
        "AuthPassword": eap_password,
        "ServerCertificateCommonName": server_cn,
        "IKESecurityAssociationParameters": {
            "EncryptionAlgorithm": "AES-256",
            "IntegrityAlgorithm": "SHA2-256",
            "DiffieHellmanGroup": 14,
            "LifeTimeInMinutes": 1440,
        },
        "ChildSecurityAssociationParameters": {
            "EncryptionAlgorithm": "AES-256",
            "IntegrityAlgorithm": "SHA2-256",
            "DiffieHellmanGroup": 14,
            "LifeTimeInMinutes": 1440,
        },
    }
    if ca_cert_der:
        ikev2["PayloadCertificateUUID"] = ca_uuid
    vpn_payload: dict[str, Any] = {
        "PayloadType": "com.apple.vpn.managed",
        "PayloadVersion": 1,
        "PayloadIdentifier": f"com.sparky-manager.vpn.{user_name}",
        "PayloadUUID": str(uuid.uuid4()),
        "PayloadDisplayName": "VPN",
        "PayloadDescription": f"{profile_name} IKEv2 VPN",
        "UserDefinedName": profile_name,
        "VPNType": "IKEv2",
        "IKEv2": ikev2,
    }
    payloads: list[dict[str, Any]] = [vpn_payload]
    if ca_cert_der:
        payloads.append(
            {
                "PayloadType": "com.apple.security.root",
                "PayloadVersion": 1,
                "PayloadIdentifier": "com.sparky-manager.ca",
                "PayloadUUID": ca_uuid,
                "PayloadDisplayName": f"{profile_name} CA",
                "PayloadDescription": (
                    "Root certificate for the sparky-manager VPN server. "
                    "Enable full trust for it in Settings after installing."
                ),
                "PayloadCertificateFileName": "sparky-manager-ca.cer",
                "PayloadContent": ca_cert_der,
            }
        )
    top: dict[str, Any] = {
        "PayloadType": "Configuration",
        "PayloadVersion": 1,
        "PayloadIdentifier": f"com.sparky-manager.profile.{user_name}",
        "PayloadUUID": str(uuid.uuid4()),
        "PayloadDisplayName": profile_name,
        "PayloadDescription": f"{profile_name} IKEv2 VPN profile",
        "PayloadContent": payloads,
    }
    return plistlib.dumps(top, fmt=plistlib.FMT_XML, sort_keys=False)


def validate_swanctl_config(text: str) -> list[str]:
    """Structural validation of a rendered swanctl.conf.

    Checks balanced braces, the required sections (pools /
    connections / secrets), the connection's version + proposals,
    a valid pool subnet, and that every EAP secret has an id and a
    secret. The real check is ``swanctl --load-all`` (the load
    itself is the validator — there is no dry-run); this catches
    render mistakes first.
    """
    problems: list[str] = []
    if not text.strip():
        return ["config is empty"]
    if text.count("{") != text.count("}"):
        problems.append("unbalanced braces in swanctl.conf")
    for section in ("pools", "connections", "secrets"):
        if not re.search(rf"^\s*{section}\s*\{{", text, re.MULTILINE):
            problems.append(f"config is missing the '{section}' section")
    if CONNECTION_NAME not in text:
        problems.append(f"config is missing the '{CONNECTION_NAME}' connection")
    if "version = 2" not in text:
        problems.append("connection is not IKEv2 (version = 2)")
    if "aes256-sha256-modp2048" not in text:
        problems.append("config is missing the aes256-sha256-modp2048 proposals")
    if "auth = eap-mschapv2" not in text:
        problems.append("config is missing eap-mschapv2 remote auth")
    match = re.search(r"addrs\s*=\s*([0-9./]+)", text)
    if match:
        try:
            ipaddress.ip_network(match.group(1), strict=False)
        except ValueError:
            problems.append(f"pool addrs is not a valid subnet: {match.group(1)!r}")
    else:
        problems.append("pool has no addrs")
    secrets_block = re.search(r"secrets\s*\{(.*)\}\s*$", text, re.DOTALL)
    if secrets_block:
        block = secrets_block.group(1)
        for entry in re.finditer(r"eap-user-\d+\s*\{(.*?)\}", block, re.DOTALL):
            body = entry.group(1)
            if "id =" not in body:
                problems.append("an EAP secret has no id")
            if "secret =" not in body:
                problems.append("an EAP secret has no secret")
    return problems
